"""Storage adapters and verified retention lifecycle management for Efso Radar backups.

Implements an offline-testable storage adapter interface, a simulated GitHub Release
storage adapter for the single rolling-release architecture, and verified retention
policy evaluation enforcing 14-day rolling expiration, content verification,
inventory revalidation, budget enforcement, and the immutable safety rule:
NEVER DELETE THE LAST VERIFIED BACKUP.
"""
from __future__ import annotations

import abc
import hashlib
import logging
import re
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from typing import Any

from efso_radar.backup.envelope import decrypt_envelope

logger = logging.getLogger("efso-radar.backup.retention")

BACKUP_FILENAME_REGEX = re.compile(
    r"^efso_backup_(\d{8})_(\d{6})_([0-9a-fA-F]+)\.efbk$"
)


class StorageError(Exception):
    """Base exception for storage adapter failures."""
    pass


class RetentionPolicyViolationError(Exception):
    """Raised when an operation would violate safety invariants (e.g. deleting last verified backup)."""
    pass


class StaleInventoryError(RetentionPolicyViolationError):
    """Raised when remote inventory has changed concurrently between plan and execution."""
    pass


@dataclass(frozen=True)
class BackupAsset:
    """Represents a remote backup asset hosted in storage."""
    asset_id: str
    name: str
    size_bytes: int
    created_at_utc: datetime
    sha256: str = ""
    download_url: str = ""


@dataclass(frozen=True)
class VerifiedRecoveryPoint:
    """Represents a backup asset whose content has been authenticated and verified."""
    asset: BackupAsset
    schema_version: int
    plaintext_sha256: str
    verified_at_utc: datetime


@dataclass(frozen=True)
class RetentionPlan:
    """Action plan generated by evaluating retention policy against verified assets."""
    retained_assets: list[BackupAsset]
    assets_to_delete: list[BackupAsset]
    reasons: list[str]
    total_retained_bytes: int
    inventory_fingerprint: str
    upload_blocked: bool = False


class StorageAdapter(abc.ABC):
    """Abstract interface for remote backup asset storage."""

    @abc.abstractmethod
    def upload_asset(self, asset_name: str, data: bytes) -> BackupAsset:
        """Upload an encrypted backup asset and verify remote receipt."""
        raise NotImplementedError

    @abc.abstractmethod
    def download_asset(self, asset_id: str) -> bytes:
        """Download asset bytes by unique identifier."""
        raise NotImplementedError

    @abc.abstractmethod
    def list_assets(self) -> list[BackupAsset]:
        """List all available backup assets sorted newest first."""
        raise NotImplementedError

    @abc.abstractmethod
    def delete_asset(self, asset_id: str) -> bool:
        """Permanently delete an asset from remote storage."""
        raise NotImplementedError

    @abc.abstractmethod
    def get_inventory_fingerprint(self) -> str:
        """Return cryptographic hash of current asset inventory for concurrency verification."""
        raise NotImplementedError


class MockGitHubReleaseStorageAdapter(StorageAdapter):
    """In-memory hermetic storage adapter modeling GitHub Releases API.

    Implements a single rolling Release (`rolling-backups`) hosting dated .efbk assets.
    Performs verified uploads, SHA-256 verification, inventory fingerprinting,
    and simulated asset deletion without real network calls.
    """

    def __init__(self, release_tag: str = "rolling-backups", max_capacity_bytes: int = 1024 * 1024 * 1024):
        self.release_tag = release_tag
        self.max_capacity_bytes = max_capacity_bytes
        self._assets: dict[str, tuple[BackupAsset, bytes]] = {}
        self._asset_counter = 1000

    def upload_asset(self, asset_name: str, data: bytes) -> BackupAsset:
        current_total = sum(a.size_bytes for a, _ in self._assets.values())
        if current_total + len(data) > self.max_capacity_bytes:
            raise StorageError(
                f"Storage capacity exceeded: current {current_total} + {len(data)} > {self.max_capacity_bytes}"
            )

        # Parse timestamp from asset name if present
        match = BACKUP_FILENAME_REGEX.match(asset_name)
        if match:
            date_str, time_str, _ = match.groups()
            created_at = datetime.strptime(f"{date_str}{time_str}", "%Y%m%d%H%M%S").replace(tzinfo=timezone.utc)
        else:
            created_at = datetime.now(timezone.utc)

        self._asset_counter += 1
        asset_id = f"asset-{self._asset_counter}"
        sha256 = hashlib.sha256(data).hexdigest()

        asset = BackupAsset(
            asset_id=asset_id,
            name=asset_name,
            size_bytes=len(data),
            created_at_utc=created_at,
            sha256=sha256,
            download_url=f"https://github.mock/releases/assets/{asset_id}",
        )

        self._assets[asset_id] = (asset, data)
        logger.info("Mock upload verified for %s (%d bytes)", asset_name, len(data))
        return asset

    def download_asset(self, asset_id: str) -> bytes:
        if asset_id not in self._assets:
            raise StorageError(f"Asset not found: {asset_id}")
        return self._assets[asset_id][1]

    def list_assets(self) -> list[BackupAsset]:
        assets = [a for a, _ in self._assets.values()]
        return sorted(assets, key=lambda a: a.created_at_utc, reverse=True)

    def delete_asset(self, asset_id: str) -> bool:
        if asset_id in self._assets:
            del self._assets[asset_id]
            logger.info("Deleted asset %s from storage", asset_id)
            return True
        return False

    def get_inventory_fingerprint(self) -> str:
        h = hashlib.sha256()
        for a in self.list_assets():
            h.update(f"{a.asset_id}:{a.name}:{a.size_bytes}:{a.sha256};".encode("utf-8"))
        return h.hexdigest()


class RetentionPolicyManager:
    """Evaluates retention rules and enforces verified recovery point invariants."""

    def __init__(
        self,
        max_retention_days: int = 14,
        min_recovery_points: int = 2,
        max_storage_budget_bytes: int = 500 * 1024 * 1024,  # 500 MB
    ):
        self.max_retention_days = max_retention_days
        self.min_recovery_points = min_recovery_points
        self.max_storage_budget_bytes = max_storage_budget_bytes

    def verify_inventory(
        self,
        storage: StorageAdapter,
        decryption_key: bytes,
        expected_schema_version: int = 5,
    ) -> tuple[list[VerifiedRecoveryPoint], list[str]]:
        """Download and fully verify all assets against SQLite integrity and schema rules.

        Executes full restore verification in an ephemeral staging directory:
        validates payload SHA-256 against manifest, verifies SQLite PRAGMA integrity_check,
        confirms schema migrations version matches expected_schema_version, and validates
        essential ledgers (delivery outbox and experiment budget).

        Assets that fail download, envelope decryption, SQLite integrity, or ledger
        validation are flagged and NOT counted towards verified recovery points.
        """
        import shutil
        from efso_radar.backup.restore import verify_restore_archive

        verified_points: list[VerifiedRecoveryPoint] = []
        issues: list[str] = []

        assets = storage.list_assets()
        for asset in assets:
            try:
                data = storage.download_asset(asset.asset_id)
                restore_res = verify_restore_archive(
                    envelope_bytes=data,
                    key=decryption_key,
                    staging_dir=None,  # Ephemeral dedicated system temp
                    expected_schema_version=expected_schema_version,
                )
                if not restore_res.success:
                    issues.append(f"Asset '{asset.name}' ({asset.asset_id}) failed restore verification")
                    continue

                # Clean up ephemeral verification staging directory immediately
                try:
                    if restore_res.staging_dir.exists():
                        shutil.rmtree(restore_res.staging_dir, ignore_errors=True)
                except Exception:
                    pass

                schema_ver = restore_res.manifest.get("schema_version", 0)
                plaintext_sha = restore_res.manifest.get("plaintext_sha256", "")

                verified_points.append(
                    VerifiedRecoveryPoint(
                        asset=asset,
                        schema_version=schema_ver,
                        plaintext_sha256=plaintext_sha,
                        verified_at_utc=datetime.now(timezone.utc),
                    )
                )
            except Exception as exc:
                issues.append(f"Asset '{asset.name}' ({asset.asset_id}) failed verification: {exc}")

        return verified_points, issues

    def evaluate_retention(
        self,
        verified_points: list[VerifiedRecoveryPoint],
        all_assets: list[BackupAsset],
        inventory_fingerprint: str,
        now: datetime | None = None,
    ) -> RetentionPlan:
        """Calculate which assets to keep and which to delete based strictly on VERIFIED recovery points.

        Enforces:
        1. Retention window (items older than max_retention_days marked for pruning).
        2. Invariant 1: NEVER delete the newest verified backup.
        3. Invariant 2: Always preserve at least min_recovery_points verified points regardless of age.
        4. Budget enforcement: Prefer halting new uploads over deleting below min_recovery_points.
        5. Concurrency defense: Binds inventory_fingerprint to detect stale plans.

        Args:
            verified_points: Assets that passed cryptographic verification.
            all_assets: Current complete asset list from storage.
            inventory_fingerprint: SHA-256 fingerprint of current inventory.
            now: Reference timestamp for age calculation.

        Returns:
            RetentionPlan detailing retained and deletable assets.
        """
        ref_now = now or datetime.now(timezone.utc)
        cutoff_date = ref_now - timedelta(days=self.max_retention_days)

        # Map verified assets
        verified_asset_ids = {vp.asset.asset_id for vp in verified_points}
        sorted_verified = sorted(verified_points, key=lambda vp: vp.asset.created_at_utc, reverse=True)

        retained: list[BackupAsset] = []
        candidates_for_deletion: list[BackupAsset] = []
        reasons: list[str] = []
        upload_blocked = False

        # Invariant: If verified points <= min_recovery_points, keep ALL verified points unconditionally
        if len(sorted_verified) <= self.min_recovery_points:
            reasons.append(
                f"Verified recovery points ({len(sorted_verified)}) <= required minimum ({self.min_recovery_points}). "
                "Preserving all verified backups."
            )
            retained = [vp.asset for vp in sorted_verified]
        else:
            # We have more than min_recovery_points; evaluate age
            for idx, vp in enumerate(sorted_verified):
                if idx < self.min_recovery_points:
                    retained.append(vp.asset)
                elif vp.asset.created_at_utc < cutoff_date:
                    candidates_for_deletion.append(vp.asset)
                else:
                    retained.append(vp.asset)

        # Invariant 1: Ensure newest verified backup is NEVER in deletion list
        if sorted_verified:
            newest_verified_asset = sorted_verified[0].asset
            if newest_verified_asset in candidates_for_deletion:
                candidates_for_deletion.remove(newest_verified_asset)
                retained.append(newest_verified_asset)
                reasons.append("Protected newest verified backup from deletion.")

        # Invariant 2: Ensure at least min_recovery_points verified backups retained
        retained_verified_count = sum(1 for a in retained if a.asset_id in verified_asset_ids)
        while retained_verified_count < self.min_recovery_points and candidates_for_deletion:
            rescued = candidates_for_deletion.pop(0)
            retained.append(rescued)
            if rescued.asset_id in verified_asset_ids:
                retained_verified_count += 1
            reasons.append(f"Preserved {rescued.name} to maintain minimum verified recovery points.")

        # Storage budget evaluation
        total_retained_bytes = sum(a.size_bytes for a in retained)
        if total_retained_bytes > self.max_storage_budget_bytes:
            # Check if we can prune older retained assets that are above min_recovery_points
            prunable = [a for a in retained[self.min_recovery_points:]]
            while prunable and total_retained_bytes > self.max_storage_budget_bytes:
                candidate = prunable.pop()
                retained.remove(candidate)
                candidates_for_deletion.append(candidate)
                total_retained_bytes -= candidate.size_bytes
                reasons.append(f"Pruned {candidate.name} to satisfy storage budget.")

            # If still exceeding budget and cannot delete below min_recovery_points: PREFER HALTING UPLOADS
            if total_retained_bytes > self.max_storage_budget_bytes:
                upload_blocked = True
                reasons.append(
                    f"Storage budget exceeded ({total_retained_bytes} > {self.max_storage_budget_bytes}) "
                    f"but cannot delete below min_recovery_points ({self.min_recovery_points}). "
                    "Halting new backup uploads to prevent unsafe data loss."
                )

        retained.sort(key=lambda a: a.created_at_utc, reverse=True)

        logger.info(
            "Retention evaluation: %d retained, %d to delete, upload_blocked=%s (Size: %d bytes)",
            len(retained),
            len(candidates_for_deletion),
            upload_blocked,
            total_retained_bytes,
        )

        return RetentionPlan(
            retained_assets=retained,
            assets_to_delete=candidates_for_deletion,
            reasons=reasons,
            total_retained_bytes=total_retained_bytes,
            inventory_fingerprint=inventory_fingerprint,
            upload_blocked=upload_blocked,
        )

    def apply_retention(
        self,
        storage: StorageAdapter,
        plan: RetentionPlan,
    ) -> list[str]:
        """Execute deletion of planned assets with pre-deletion inventory revalidation.

        Args:
            storage: Storage adapter to delete assets from.
            plan: Retention plan from evaluate_retention.

        Returns:
            List of successfully deleted asset IDs.

        Raises:
            StaleInventoryError: If inventory changed concurrently since plan generation.
            RetentionPolicyViolationError: If executing plan would violate recovery invariants.
        """
        # Concurrency safety gate: revalidate inventory fingerprint immediately before deletion
        current_fingerprint = storage.get_inventory_fingerprint()
        if current_fingerprint != plan.inventory_fingerprint:
            raise StaleInventoryError(
                "Remote storage inventory changed concurrently since retention plan generation. "
                "Aborting deletion to prevent deleting unexpected assets."
            )

        current_assets = storage.list_assets()
        remaining_count = len(current_assets) - len(plan.assets_to_delete)
        if remaining_count < self.min_recovery_points:
            raise RetentionPolicyViolationError(
                f"Aborting deletion: would leave {remaining_count} assets, below required minimum {self.min_recovery_points}"
            )

        deleted_ids: list[str] = []
        for asset in plan.assets_to_delete:
            success = storage.delete_asset(asset.asset_id)
            if success:
                deleted_ids.append(asset.asset_id)

        return deleted_ids
