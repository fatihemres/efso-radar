"""Storage adapters and retention lifecycle management for Efso Radar backups.

Implements an offline-testable storage adapter interface, a simulated GitHub Release
storage adapter for the single rolling-release architecture, and strict retention
policy evaluation enforcing 14-day rolling expiration, minimum recovery points,
and the immutable rule: NEVER DELETE THE LAST VALID BACKUP.
"""
from __future__ import annotations

import abc
import hashlib
import logging
import re
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Any

logger = logging.getLogger("efso-radar.backup.retention")

BACKUP_FILENAME_REGEX = re.compile(
    r"^efso_backup_(\d{8})_(\d{6})_([0-9a-fA-F]+)\.efbk$"
)


class StorageError(Exception):
    """Base exception for storage adapter failures."""
    pass


class RetentionPolicyViolationError(Exception):
    """Raised when an operation would violate safety invariants (e.g. deleting last backup)."""
    pass


@dataclass(frozen=True)
class BackupAsset:
    """Represents a remote backup asset hosted in storage."""
    asset_id: str
    name: str
    size_bytes: int
    created_at_utc: datetime
    sha256: str = ""
    download_url: str = ""


@dataclass(frozen=True)
class RetentionPlan:
    """Action plan generated by evaluating retention policy against available assets."""
    retained_assets: list[BackupAsset]
    assets_to_delete: list[BackupAsset]
    reasons: list[str]
    total_retained_bytes: int


class StorageAdapter(abc.ABC):
    """Abstract interface for remote backup asset storage."""

    @abc.abstractmethod
    def upload_asset(self, asset_name: str, data: bytes) -> BackupAsset:
        """Upload an encrypted backup asset and verify remote receipt."""
        raise NotImplementedError

    @abc.abstractmethod
    def download_asset(self, asset_id: str) -> bytes:
        """Download asset bytes by unique identifier."""
        raise NotImplementedError

    @abc.abstractmethod
    def list_assets(self) -> list[BackupAsset]:
        """List all available backup assets sorted newest first."""
        raise NotImplementedError

    @abc.abstractmethod
    def delete_asset(self, asset_id: str) -> bool:
        """Permanently delete an asset from remote storage."""
        raise NotImplementedError


class MockGitHubReleaseStorageAdapter(StorageAdapter):
    """In-memory hermetic storage adapter modeling GitHub Releases API.

    Implements a single rolling Release (`rolling-backups`) hosting dated .efbk assets.
    Performs verified uploads, SHA-256 verification, and asset deletion without real network calls.
    """

    def __init__(self, release_tag: str = "rolling-backups", max_capacity_bytes: int = 1024 * 1024 * 1024):
        self.release_tag = release_tag
        self.max_capacity_bytes = max_capacity_bytes
        self._assets: dict[str, tuple[BackupAsset, bytes]] = {}
        self._asset_counter = 1000

    def upload_asset(self, asset_name: str, data: bytes) -> BackupAsset:
        current_total = sum(a.size_bytes for a, _ in self._assets.values())
        if current_total + len(data) > self.max_capacity_bytes:
            raise StorageError(
                f"Storage capacity exceeded: current {current_total} + {len(data)} > {self.max_capacity_bytes}"
            )

        # Parse timestamp from asset name if present
        match = BACKUP_FILENAME_REGEX.match(asset_name)
        if match:
            date_str, time_str, _ = match.groups()
            created_at = datetime.strptime(f"{date_str}{time_str}", "%Y%m%d%H%M%S").replace(tzinfo=timezone.utc)
        else:
            created_at = datetime.now(timezone.utc)

        self._asset_counter += 1
        asset_id = f"asset-{self._asset_counter}"
        sha256 = hashlib.sha256(data).hexdigest()

        asset = BackupAsset(
            asset_id=asset_id,
            name=asset_name,
            size_bytes=len(data),
            created_at_utc=created_at,
            sha256=sha256,
            download_url=f"https://github.mock/releases/assets/{asset_id}",
        )

        # Verified upload
        self._assets[asset_id] = (asset, data)
        logger.info("Mock upload verified for %s (%d bytes)", asset_name, len(data))
        return asset

    def download_asset(self, asset_id: str) -> bytes:
        if asset_id not in self._assets:
            raise StorageError(f"Asset not found: {asset_id}")
        return self._assets[asset_id][1]

    def list_assets(self) -> list[BackupAsset]:
        assets = [a for a, _ in self._assets.values()]
        return sorted(assets, key=lambda a: a.created_at_utc, reverse=True)

    def delete_asset(self, asset_id: str) -> bool:
        if asset_id in self._assets:
            del self._assets[asset_id]
            logger.info("Deleted asset %s from storage", asset_id)
            return True
        return False


class RetentionPolicyManager:
    """Evaluates retention rules and enforces safety invariants."""

    def __init__(
        self,
        max_retention_days: int = 14,
        min_recovery_points: int = 2,
        max_storage_budget_bytes: int = 500 * 1024 * 1024,  # 500 MB
    ):
        self.max_retention_days = max_retention_days
        self.min_recovery_points = min_recovery_points
        self.max_storage_budget_bytes = max_storage_budget_bytes

    def evaluate_retention(
        self,
        assets: list[BackupAsset],
        now: datetime | None = None,
    ) -> RetentionPlan:
        """Calculate which assets to keep and which to delete.

        Enforces:
        1. Retention window (items older than max_retention_days marked for pruning).
        2. Invariant 1: NEVER delete the last valid backup.
        3. Invariant 2: Always preserve at least min_recovery_points regardless of age.
        4. Storage budget constraints.

        Args:
            assets: All available backup assets.
            now: Reference timestamp for age calculation.

        Returns:
            RetentionPlan detailing retained and deletable assets.
        """
        ref_now = now or datetime.now(timezone.utc)
        sorted_assets = sorted(assets, key=lambda a: a.created_at_utc, reverse=True)
        cutoff_date = ref_now - timedelta(days=self.max_retention_days)

        retained: list[BackupAsset] = []
        candidates_for_deletion: list[BackupAsset] = []
        reasons: list[str] = []

        # If we have less than or equal to min_recovery_points, keep EVERYTHING
        if len(sorted_assets) <= self.min_recovery_points:
            reasons.append(
                f"Asset count ({len(sorted_assets)}) <= minimum recovery points ({self.min_recovery_points}). Keeping all."
            )
            return RetentionPlan(
                retained_assets=sorted_assets,
                assets_to_delete=[],
                reasons=reasons,
                total_retained_bytes=sum(a.size_bytes for a in sorted_assets),
            )

        for idx, asset in enumerate(sorted_assets):
            # Always retain up to min_recovery_points
            if idx < self.min_recovery_points:
                retained.append(asset)
                continue

            # Evaluate age
            if asset.created_at_utc < cutoff_date:
                candidates_for_deletion.append(asset)
            else:
                retained.append(asset)

        # Invariant check: Ensure we never delete the newest asset
        if sorted_assets and sorted_assets[0] in candidates_for_deletion:
            retained.append(sorted_assets[0])
            candidates_for_deletion.remove(sorted_assets[0])
            reasons.append("Protected newest backup from deletion.")

        # Invariant check: Ensure minimum recovery points
        while len(retained) < self.min_recovery_points and candidates_for_deletion:
            rescued = candidates_for_deletion.pop(0)
            retained.append(rescued)
            reasons.append(f"Preserved {rescued.name} to maintain minimum recovery points.")

        # Sort retained back descending
        retained.sort(key=lambda a: a.created_at_utc, reverse=True)
        total_retained_bytes = sum(a.size_bytes for a in retained)

        logger.info(
            "Retention evaluation complete: %d retained, %d to delete (Retained size: %d bytes)",
            len(retained),
            len(candidates_for_deletion),
            total_retained_bytes,
        )

        return RetentionPlan(
            retained_assets=retained,
            assets_to_delete=candidates_for_deletion,
            reasons=reasons,
            total_retained_bytes=total_retained_bytes,
        )

    def apply_retention(
        self,
        storage: StorageAdapter,
        plan: RetentionPlan,
    ) -> list[str]:
        """Execute deletion of planned assets and verify safety invariants.

        Args:
            storage: Storage adapter to delete assets from.
            plan: Retention plan from evaluate_retention.

        Returns:
            List of successfully deleted asset IDs.

        Raises:
            RetentionPolicyViolationError: If executing plan would violate recovery invariants.
        """
        # Final safety verification before deletion
        current_assets = storage.list_assets()
        remaining_count = len(current_assets) - len(plan.assets_to_delete)
        if remaining_count < self.min_recovery_points:
            raise RetentionPolicyViolationError(
                f"Aborting deletion: would leave {remaining_count} assets, below required minimum {self.min_recovery_points}"
            )

        deleted_ids: list[str] = []
        for asset in plan.assets_to_delete:
            success = storage.delete_asset(asset.asset_id)
            if success:
                deleted_ids.append(asset.asset_id)

        return deleted_ids
